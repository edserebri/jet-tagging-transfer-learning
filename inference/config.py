"""
Configuration for the inference service.

По умолчанию используется представление джета из проекта:
до 200 конституентов, по 7 признаков на каждый после preprocessing,
то есть вход формы [batch, 200, 7].

Параметры вынесены в конфиг, чтобы:
- было понятно, какие размерности ожидает сервис,
- можно было легко поменять их при замене mock-модели на реальную,
- упростить тестирование и отладку.
"""

from pydantic import BaseModel


class Settings(BaseModel):
    # Размерность входного представления джета
    n_constituents: int = 200
    n_features: int = 7

    # Бинарная классификация: сигнал / фон
    n_classes: int = 2

    # Параметры mock student-модели
    # Намеренно маленькая модель для быстрого CPU-инференса
    hidden_dim: int = 64
    seed: int = 42

    # Ограничение на размер батча,
    # чтобы защититься от слишком больших запросов
    max_batch_size: int = 2048


# Единственный экземпляр конфига,
# используется всеми компонентами инференс-сервиса
settings = Settings()
